  await page.getByLabel('Einheit', { exact: true }).fill('g')
  await page.getByLabel('Zutat', { exact: true }).fill('Mehl')
  await page.getByRole('button', { name: '+ Rezeptteil hinzufügen' }).click()
  await page.getByLabel('Name des Teils').fill('Glasur')
  await page.getByLabel('Zubereitung', { exact: true }).nth(1).fill('Schokolade schmelzen.')
  await page.getByRole('button', { name: '+ Rezeptteil hinzufügen' }).click()
  await page.getByLabel('Name des Teils').nth(1).fill('Füllung')
  await page.getByLabel('Zubereitung', { exact: true }).nth(2).fill('Creme aufschlagen.')
  // Small valid PNG; server decoding and conversion are exercised.
  await page.getByLabel('Foto', { exact: true }).setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aWQAAAABJRU5ErkJggg==', 'base64') })
  await page.getByRole('button', { name: 'Rezept speichern' }).click()
