test('Felix edits original public recipes directly on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, 'felix')
  await page.goto('/recipe/48')
  await expect(page.getByRole('link', { name: 'Rezept kopieren' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Bearbeiten', exact: true }).click()
  await expect(page.getByLabel('Name des Teils').first()).toHaveValue('Pizzateig')
  await expect(page.getByLabel('Portionen des Rezepts')).toHaveValue('4')
  await page.getByRole('combobox', { name: 'Kategorie', exact: true }).selectOption('sonstiges')
  await page.getByLabel('Tags hinzufügen').fill('Familienpizza')
  await page.getByRole('button', { name: 'Tag hinzufügen', exact: true }).click()
  await page.getByRole('button', { name: 'Rezept speichern' }).click()
  await expect(page).toHaveURL('/recipe/48')
  await expect(page.getByRole('heading', { name: 'Pizzateig', exact: true }).first()).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Pizzasoße', exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Abmelden' }).click()
  await page.goto('/recipe/48')
  await expect(page.getByRole('link', { name: 'Familienpizza', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Bearbeiten', exact: true })).toHaveCount(0)
  const photo = page.getByRole('img', { name: 'Pizza', exact: true })
  await expect.poll(() => photo.evaluate(img => img.naturalWidth)).toBeGreaterThan(0)
  const exposed = await page.request.get('/public/data/images/pizza.jpg')
  expect(exposed.status()).toBe(403)
})

test('favourites persist per account and category/tag filters combine', async ({ page }) => {
  await login(page, 'alice')
  await page.goto('/recipe/48')
  await page.getByRole('button', { name: '☆ Zu Favouriten hinzufügen', exact: true }).click()
  await expect(page.getByRole('button', { name: '★ Aus Favouriten entfernen', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '★ Favouriten', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pizza', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Pizza', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Abmelden' }).click()
  await login(page, 'bob')
  await page.getByRole('link', { name: '★ Favouriten', exact: true }).click()
  await expect(page.getByText('Noch keine Favouriten. Markiere ein Rezept mit einem Stern.')).toBeVisible()
  await page.getByRole('link', { name: 'Alle Rezepte', exact: true }).click()
  await page.getByRole('combobox', { name: 'Kategorie', exact: true }).selectOption('Suppe')
  await page.getByRole('checkbox', { name: 'Mama-Rezept', exact: true }).check()
  await expect(page.getByRole('heading', { name: 'Tomatensuppe', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Pizza', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Filter zurücksetzen', exact: true }).click()
  await page.getByRole('button', { name: 'Abmelden' }).click()
  await login(page, 'alice')
  await page.getByRole('link', { name: '★ Favouriten', exact: true }).click()
  await page.getByRole('button', { name: 'Pizza: Aus Favouriten entfernen', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pizza', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Pizza', exact: true })).toHaveCount(0)
})

